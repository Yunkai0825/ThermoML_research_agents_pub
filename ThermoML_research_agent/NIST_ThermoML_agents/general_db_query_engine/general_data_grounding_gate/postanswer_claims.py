"""Ground post-answer factual prose before it enters a ThermoML handover.

The working answer was already checked in the ReAct loop. The parallel
post-answer workers can author new core claims, summaries and source
explanations; this checker applies the same gate to those new strings.
Deterministic ledgers and future-task suggestions are not answer claims.
"""

from __future__ import annotations

from . import profile

import logging
from copy import deepcopy
from typing import Any

from .grounding_gate import (
    _BLOCK_ANCHOR_RE,
    FLAGS_HEADER,
    GateReport,
    _cited_dois,
    _literals,
    build_flags_note,
    gate_enabled,
    gate_switched_off,
    run_data_grounding_gate,
)
from .inspection_harvest import harvest_inspections

_POSTANSWER_HEADER = "[POSTANSWER DATA FLAGS]"
_log = logging.getLogger(__name__)
_SKIP_BRANCHES = {
    "answer", "core_claims", "summary", "follow_up_suggestions",
    "data_inspections", "fit_results", "id_catalog_snapshot",
    # These describe the dispatched request, not a new measured result.
    "system", "state",
}
_NON_CLAIM_KEYS = {
    "doi", "block", "block_number", "lit_num_id", "blksubsys_id",
    "inspection_id", "status", "endpoint_quality", "bases",
    "properties", "solvents",
}


def _is_non_claim_key(key: str) -> bool:
    lower = key.casefold()
    return (
        lower in _NON_CLAIM_KEYS
        or lower.endswith("_id")
        or lower.endswith("_ids")
    )


def _unique_scope(text: str) -> str | None:
    """Use an explicit citation only if it names one unambiguous source."""
    # Working-answer diagnostics quote inspection calls and candidate IDs.
    # They are generated by the gate, not citations authored by the agent.
    authored = text
    for header in (FLAGS_HEADER, _POSTANSWER_HEADER):
        authored = authored.partition(header)[0]
    qualified: set[tuple[str, str]] = set()
    bare: set[str] = set()
    for match in _BLOCK_ANCHOR_RE.finditer(authored):
        lit, block = match.group(1), match.group(2)
        if lit:
            qualified.add((lit, block))
        else:
            bare.add(block)
    if len(qualified) > 1 or len(bare) > 1:
        return None
    dois = _cited_dois(authored)
    if len(dois) > 1:
        return None
    if qualified:
        lit, block = next(iter(qualified))
        # A bare block is the same citation when it names that very block.
        return f"{lit}::{block}" if not bare or bare == {block} else None
    if bare:
        return next(iter(bare))
    return f"DOI {dois[0]}" if len(dois) == 1 else None


def _has_citation(text: str) -> bool:
    return bool(_BLOCK_ANCHOR_RE.search(text) or _cited_dois(text))


def _local_scope(node: dict[str, Any]) -> str | None:
    lit = node.get("lit_num_id")
    block = node.get("block") or node.get("block_number")
    if isinstance(block, str):
        candidate = f"{lit}::{block}" if isinstance(lit, str) else block
        if _BLOCK_ANCHOR_RE.fullmatch(candidate):
            return candidate
    doi = node.get("doi")
    if isinstance(doi, str):
        dois = _cited_dois(doi)
        if len(dois) == 1:
            return f"DOI {dois[0]}"
    return None


def _local_doi(node: dict[str, Any]) -> str | None:
    doi = node.get("doi")
    if not isinstance(doi, str):
        return None
    dois = _cited_dois(doi)
    return dois[0] if len(dois) == 1 else None


def _ambiguous_report(path: str, text: str) -> GateReport:
    tokens = [token for _, token, _ in _literals(text)]
    return GateReport(
        ok=False,
        violations=[{
            "kind": "UNINSPECTED_BLOCK",
            "anchor": path,
            "block_number": None,
            "lit_id": None,
            "literals": tokens,
            "detail": (
                "This post-answer claim has numeric data but no unique "
                "inspected source can be assigned from its citation or "
                "the checked working answer"
            ),
            "suggested_call": (
                "cite the exact inspected GLOBlit_N::PROPblock_N or "
                "RXNblock_N beside this claim"
            ),
        }],
    )


def _postanswer_gate_active(tools) -> bool:
    """Use the same active-tool eligibility as the working ReAct gate."""
    return not profile.is_legacy_mode() and gate_enabled(tools)


def postanswer_checker_for_tools(tools):
    """Return the post-assembly checker for inspection-capable gated runs."""
    return check_postanswer_claims if _postanswer_gate_active(tools) else None


def core_claims_source_suffix(tools) -> str:
    """Preserve cited numeric evidence when the grounding gate is active."""
    if not _postanswer_gate_active(tools):
        return ""
    return (
        "\n\nFor numeric core claims, preserve the exact DOI and/or "
        "block reference (GLOBlit_N and PROPblock_N/RXNblock_N, including "
        "qualified forms) that explicitly accompanies the same numeric "
        "statement in the completed answer. This limited exception to "
        "the no-identifiers rule allows copying those existing source "
        "citations into core_claims. Keep each citation beside the "
        "statement it supports. Never invent, infer, alter, or transfer "
        "a citation, numeric value, unit, or evidence. If no explicit "
        "source accompanies a numeric statement in the answer, omit "
        "that number rather than guess a citation."
    )


def check_postanswer_claims(
    *,
    assembled: dict[str, Any],
    agent_answer: str,
    tool_history: list[dict] | None,
) -> dict[str, Any]:
    """Flag newly authored factual fields using the central grounding gate.

    The process-level gate-off switch controls this post-assembly pass
    just as it controls working-answer enforcement.
    The callback returns a copy and keeps the response schema unchanged.
    """
    if profile.is_legacy_mode() or gate_switched_off():
        return assembled
    checked = deepcopy(assembled)
    inspections = harvest_inspections(tool_history)
    parent_scope = _unique_scope(agent_answer)
    flagged_paths: list[str] = []
    checked_paths: list[str] = []
    numeric_flags: list[str] = []

    def _check(
        text: str, path: str, local_scope: str | None = None,
        local_doi: str | None = None,
    ) -> str:
        if not isinstance(text, str) or not _literals(text):
            return text
        checked_paths.append(path)
        # An in-field citation is evaluated as written, including multiple
        # explicit blocks. A source object may lend its identity only to
        # citation-free factual fields; conflicting explicit IDs are flagged.
        anchors = list(_BLOCK_ANCHOR_RE.finditer(text))
        dois = _cited_dois(text)
        expected_block = (
            _BLOCK_ANCHOR_RE.fullmatch(local_scope) if local_scope else None
        )
        # A bare block spelling may refer to the object's qualified block.
        # Every explicitly different block or DOI remains a conflict, even
        # when another inspected source could support the quoted value.
        conflict = bool(
            expected_block and any(
                anchor.group(2) != expected_block.group(2)
                or (
                    anchor.group(1) is not None
                    and expected_block.group(1) is not None
                    and anchor.group(1) != expected_block.group(1)
                )
                for anchor in anchors
            )
            or local_doi and any(doi != local_doi for doi in dois)
        )
        if conflict:
            report = _ambiguous_report(path, text)
        else:
            source_text = text
            if not _has_citation(text):
                scope = local_scope or parent_scope
                if scope is None:
                    report = _ambiguous_report(path, text)
                else:
                    source_text = f"{scope}\n{text}"
                    report = run_data_grounding_gate(
                        source_text, tool_history, inspections=inspections,
                    )
            else:
                report = run_data_grounding_gate(
                    source_text, tool_history, inspections=inspections,
                )
            if (report.ok and len(report.evidence.get("literal_verdicts", []))
                    < len(_literals(text))):
                report = _ambiguous_report(path, text)
        if report.ok:
            return text
        flagged_paths.append(path)
        return (
            text + f"\n\n[POSTANSWER FIELD: {path}]"
            + build_flags_note(report)
        )

    claims = checked.get("core_claims")
    if isinstance(claims, list):
        for index, claim in enumerate(claims):
            if isinstance(claim, str):
                claims[index] = _check(claim, f"core_claims[{index}]")
    if isinstance(checked.get("summary"), str):
        checked["summary"] = _check(checked["summary"], "summary")

    def _walk(
        node: Any, path: str, inherited_scope: str | None = None,
        inherited_doi: str | None = None,
    ) -> None:
        """Check post-answer-authored factual leaves without changing types."""
        if isinstance(node, dict):
            scope = _local_scope(node) or inherited_scope
            doi = _local_doi(node) or inherited_doi
            for key, value in node.items():
                if key in _SKIP_BRANCHES or _is_non_claim_key(key):
                    continue
                field_path = f"{path}.{key}" if path else key
                if isinstance(value, str):
                    node[key] = _check(value, field_path, scope, doi)
                else:
                    _walk(value, field_path, scope, doi)
        elif isinstance(node, list):
            for index, value in enumerate(node):
                field_path = f"{path}[{index}]"
                if isinstance(value, str):
                    node[index] = _check(
                        value, field_path, inherited_scope, inherited_doi,
                    )
                else:
                    _walk(value, field_path, inherited_scope, inherited_doi)
        elif isinstance(node, (int, float)) and not isinstance(node, bool):
            text = str(node)
            checked_text = _check(
                text, path, inherited_scope, inherited_doi,
            )
            if checked_text != text:
                numeric_flags.append(
                    f"{path} = {text}" + checked_text[len(text):]
                )

    _walk(checked, "")
    if flagged_paths:
        checked["answer"] += (
            f"\n\n{_POSTANSWER_HEADER} Generated factual fields contain "
            "unverified numeric claims: " + ", ".join(flagged_paths)
            + ". See the flags attached to those fields or listed below."
        )
        if numeric_flags:
            checked["answer"] += "\n\n" + "\n\n".join(numeric_flags)
    _log.info(
        "Post-answer grounding pass: checked=%d fields=%s violations=%d paths=%s",
        len(checked_paths), checked_paths, len(flagged_paths), flagged_paths,
    )
    return checked
